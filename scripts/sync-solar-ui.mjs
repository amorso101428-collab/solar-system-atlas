/** Reuse the supplied solar UI declarations verbatim. Only selectors are adapted
 * to Earth's existing components; this file does not invent a second UI skin. */
import {readFile,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../integrations/solar-system-atlas/package.json',import.meta.url));
const postcss=require('postcss');
const base=new URL('../integrations/solar-system-atlas/src/styles/',import.meta.url);
const scope='.atlas.atlas[data-view]:not(.is-intro)';
const aliases={
 'navbtn--home':'.app-header .atlas-home',
 navbtn:':is(.app-header button:not(.nav-menu button),.earth-navigation button)',
 'navmenu__item--stack':'.nav-menu>button:has(small)',
 navmenu__item:'.nav-menu>button',navmenu__check:':is(.nav-menu>button[role=switch],.layer-item>button)',
 navmenu:'.nav-menu',
 archive__name:'.workspace-panel__body h1',
 archive__id:'.workspace-panel__head h2',
 archive__close:'.workspace-panel__head>button',
 archive__section:':is(.reading-chapter,.dossier-content>section,.depth-zone,.layer-list>section)',
 archive__body:':is(.reading-chapter p,.dossier-content p,.panel__hint,.notice)',
 archive__rows:'.dossier__rows',archive__row:'.dossier__rows>div',
 archive__type:'.eyebrow',archive__caption:'.species-photo figcaption',
 archive__sources:'.sources',archive__image:'.species-photo',
 archive__article:'.science-reading',archive__lead:'.reading-heading>p',
 archive__listitem:'.catalog-list>button',catalogpanel__meta:'.catalog-list small',
 catalogpanel__chips:'.tagrow',catalogpanel__chip:':is(.tag,.tbtn)',
 catalogpanel__tabs:':is(.tagrow,.species-tabs)',
 catalogpanel__search:':is(.search-label input,.coordinate-form input,.earth-search input)',
 'archive-rail__title':'.contents-label','archive-rail__list':'.archive-contents ol',
 'archive-rail':'.archive-contents',
};
const names=Object.keys(aliases).sort((a,b)=>b.length-a.length);
const matching=new RegExp('\\.('+names.join('|')+')(?![\\w-])','g');
const fonts=postcss.parse(await readFile(new URL('tokens.css',base),'utf8'));
const output=postcss.root();
output.append(postcss.comment({text:'Generated by scripts/sync-solar-ui.mjs from the original solar styles. Change the source, not these declarations.'}));
for(const node of fonts.nodes){
 if(node.type==='atrule'&&node.name==='font-face')output.append(node.clone());
 if(node.type==='rule'&&node.selector===':root')output.append(node.clone({selector:scope}));
}
for(const file of ['atlas.css','atlas-v2.css','atlas-v3.css','atlas-v4.css','holo.css','experience.css','optical.css']){
 const ast=postcss.parse(await readFile(new URL(file,base),'utf8'));
 const selected=postcss.root();
 ast.walkRules(rule=>{
  if(rule.parent.type==='atrule'&&rule.parent.name.includes('keyframes'))return;
  if(rule.selector===':root'){
   if(file==='optical.css')selected.append(rule.clone({selector:scope}));
   return;
  }
  const selectors=rule.selectors.filter(s=>{matching.lastIndex=0;return matching.test(s);}).map(s=>{
   matching.lastIndex=0;
   return scope+' '+s.replace(/^\.atlas(?:\[data-panel='open'\])?\s+/,'').replace(/\.navmenu__check input:checked/g,'.navmenu__check .switch.is-on').replace(/\.navmenu__check input/g,'.navmenu__check .switch').replace(matching,(_,name)=>aliases[name]).replace(/\bh4\b/g,':is(h3,h4)');
  });
  if(!selectors.length)return;
  const clone=rule.clone({selector:selectors.join(',\n')});
  const ancestors=[];for(let p=rule.parent;p&&p.type!=='root';p=p.parent)if(p.type==='atrule')ancestors.unshift(p);
  let container=selected;for(const ancestor of ancestors){const wrapper=ancestor.clone({nodes:[]});container.append(wrapper);container=wrapper;}
  container.append(clone);
 });
 output.append(postcss.comment({text:'Source: solar-system-atlas/src/styles/'+file}));output.append(selected.nodes);
}
// The source cursor stylesheet is used without a visual change in either atlas.
const v4=postcss.parse(await readFile(new URL('atlas-v4.css',base),'utf8'));
const cursor=postcss.root();
v4.walkRules(rule=>{const selectors=rule.selectors.filter(s=>s.startsWith('.atlas-cursor'));if(selectors.length)cursor.append(rule.clone({selector:selectors.join(',\n')}));});
await writeFile(new URL('../src/styles/solar-ui-adapter.css',import.meta.url),output.toString()+'\n');
await writeFile(new URL('../src/styles/solar-cursor.css',import.meta.url),cursor.toString()+'\n');
console.log('Original solar UI declarations synced to Earth selectors.');
