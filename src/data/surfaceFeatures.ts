/**
 * 行星表面的科学标注数据（v8 §27–§37）。
 *
 * 每条特征都带**真实的经纬度**，所以它们能被贴到球面上
 * （latLonToVector3），而不是浮在屏幕上的贴纸。
 *
 * 数据来源：NASA / USGS Astrogeology 的公开地貌与大气资料，
 * 数值取常用的公开值（直径、面积、年代、成分比例）。
 */

export interface SurfaceFeature {
  id: string
  name: string
  nameCn: string
  /** 纬度（北为正，度） */
  lat: number
  /** 经度（东为正，度） */
  lon: number
  /** 特征的角直径（度）：用来画"范围圈"，只有面状特征才有 */
  sizeDeg?: number
  /** 一行数据：直径 / 面积 / 年代 / 类型 */
  meta: { zh: string; en: string }
  kind: 'mare' | 'crater' | 'basin' | 'volcano' | 'canyon' | 'storm' | 'band' | 'pole' | 'region'
}

