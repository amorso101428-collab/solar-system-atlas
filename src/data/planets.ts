const TIDAL_LOCKED = new Set(['moon', 'charon', 'io', 'europa', 'ganymede', 'callisto', 'titan', 'triton'])

const m = (
  id: string,
  name: string,
  nameCn: string,
  orbitRadius: number,
  fallbackRadius: number,
  color: string,
  periodDays: number,
  surface: SurfaceMode = 'cratered',
  note?: string,
  texture?: string
): MoonDef => {
  const km = MOON_RADIUS_KM[id]
  return {
    id,
    name,
    nameCn,
    orbitRadius,
    radius: km === undefined ? fallbackRadius : moonVisualRadius(km),
    radiusKm: km,
    surface,
    color,
    periodDays,
    note,
    texture,
    orientation: MOON_ORIENTATION[id],
    tidalLocked: TIDAL_LOCKED.has(id),
  }
}

