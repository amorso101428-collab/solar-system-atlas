export const OBJECT_BY_ID = new Map(OBJECTS.map((object) => [object.id, object]))
export const FIRST_LAUNCH_YEAR = 1957
export const CURRENT_YEAR = 2026

/** 每个航天器的所属系统 → 返回上一级时用（方案书 §15 的层级） */
export function parentOfObject(id: string | null): { kind: 'PLANET' | 'MOON'; id: string } | null {
  if (!id) return null
  const object = OBJECT_BY_ID.get(id)
  if (!object) return null
  if (object.system === 'moon') return { kind: 'MOON', id: 'moon' }
  if (object.system === 'deep' || object.system === 'belt' || object.system === 'sun') {
    return { kind: 'PLANET', id: 'sun' }
  }
  return { kind: 'PLANET', id: object.system }
}
