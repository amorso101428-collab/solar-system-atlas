export type Locale = keyof typeof DICT

export function useT() {
  const language = useAtlasStore((state) => state.language)
  return useCallback(
    (key: keyof (typeof DICT)['en'], vars?: Record<string, string | number>) => {
      const table = DICT[language] ?? DICT.en
      let value: string = (table as Record<string, string>)[key] ?? (DICT.en as Record<string, string>)[key] ?? String(key)
      if (vars) {
        for (const [name, replacement] of Object.entries(vars)) {
          value = value.replace(new RegExp(`\\{${name}\\}`, 'g'), String(replacement))
        }
      }
      return value
    },
    [language]
  )
}

/** 取双语文案的当前语言版本 */
export function pick(text: LocalizedText | undefined, language: Locale): string {
  if (!text) return ''
  return language === 'zh' ? text.zh : text.en
}

export function usePick() {
  const language = useAtlasStore((state) => state.language)
  return useCallback((text: LocalizedText | undefined) => pick(text, language), [language])
}
